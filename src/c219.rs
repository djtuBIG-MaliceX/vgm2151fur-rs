//! Namco ASIC219 ROM -> signed samples -> Furnace.
//!
//! The C219 is the 16-voice C140-family part used by Namco NA-1/NA-2. Its
//! register file is the C140 layout with 16 voices, but the differences matter:
//!
//! ```text
//! 0x05 mode: 80 key on, 40 invert, 10 loop, 08 left invert/surround,
//!            04 noise, 01 C219 mu-law
//! start/end/loop are WORD addresses; playback advances one byte per step
//! bank 0x1F7/0x1F1/0x1F3/0x1F5 selects a 128 KB bank for voices 0-3/4-7/8-11/12-15
//! ```
//!
//! VGMPlay byte-swaps every C219 ROM payload pair before loading it. The
//! collector does the same, so the bytes here are the order the C219 core
//! fetches them. Linear bodies stay 8-bit and C219 mu-law is expanded to 8-bit
//! linear (Furnace's depth-12 upload path uses a zero `length8` for C219
//! samples); noise notes use a silent body of the source window length so
//! their duration and loop flag survive.

use std::collections::{BTreeMap, BTreeSet, HashMap};

use indexmap::IndexMap;

use crate::parity::{py_int, py_round};
use crate::vgm::{assemble_rom, VgmFile};

pub const C219_VOICES: usize = 16;
pub const C219_DEFAULT_CLOCK: u32 = 25_056_500;
pub const C219_RATE_DIVISOR: i64 = 288 * 65536;
pub const C219_FURNACE_CLOCK_MAX: u32 = 100_000_000;
/// Furnace's C219 core ticks at chipClock/1136; libvgm's reference core uses
/// clock/288. The .fur clock therefore has to be 1136/288 of the VGM clock.
pub const C219_FURNACE_CLOCK_SCALE: (u32, u32) = (1136, 288);

pub const C219_MODE_MULAW: i32 = 0x01;
pub const C219_MODE_NOISE: i32 = 0x04;
pub const C219_MODE_L_INV: i32 = 0x08;
pub const C219_MODE_LOOP: i32 = 0x10;
pub const C219_MODE_INVERT: i32 = 0x40;
pub const C219_MODE_KEYON: i32 = 0x80;

