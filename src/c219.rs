#[derive(Clone, Debug, PartialEq)]
pub struct C219Sample {
    pub start: i32,
    pub data: Vec<u8>,
    pub source_bank: i32,
    pub loop_start: Option<i32>,
    pub loop_end: Option<i32>,
    pub depth: i32,
    pub noise: bool,
    /// Length before bank-gap trailing silence is appended by the layout pass.
    pub source_length: usize,
    pub hits: Vec<C219Hit>,
}

impl Default for C219Sample {
    fn default() -> Self {
        Self {
            start: 0,
            data: Vec::new(),
            source_bank: 0,
            loop_start: None,
            loop_end: None,
            depth: 8,
            noise: false,
            source_length: 0,
            hits: Vec::new(),
        }
    }
}

impl C219Sample {
    pub fn length(&self) -> usize {
        self.data.len()
    }

    pub fn mode_freq(&self) -> i32 {
        if self.hits.is_empty() {
            return 0;
        }
        let mut freqs: IndexMap<i32, i64> = IndexMap::new();
        for h in &self.hits {
            let f = hit_played_freq(h);
            if f != 0 {
                *freqs.entry(f).or_insert(0) += 1;
            }
        }
        if freqs.is_empty() {
            return 0;
        }
        let mut best: Option<(i32, i64)> = None;
        for (f, count) in &freqs {
            match best {
                Some((_, best_count)) if *count <= best_count => {}
                _ => best = Some((*f, *count)),
            }
        }
        best.map(|(f, _)| f).unwrap_or(0)
    }

    pub fn c4_rate(&self, clock: u32) -> i32 {
        (py_int(py_round(c219_rate(clock, self.mode_freq()) * c219_rate_scale(clock))) as i32)
            .max(1000)
    }
}

/// A constant/DC body produces no sound but still eats C219 memory.
fn is_silent_body(data: &[u8], depth: i32) -> bool {
    if data.len() < 2 {
        return false;
    }
    let values: Vec<i32> = if depth == 16 {
        data.chunks_exact(2)
            .map(|c| i16::from_le_bytes([c[0], c[1]]) as i32)
            .collect()
    } else {
        data.iter()
            .map(|&b| if b >= 128 { b as i32 - 256 } else { b as i32 })
            .collect()
    };
    if values.is_empty() {
        return false;
    }
    let max = *values.iter().max().unwrap();
    let min = *values.iter().min().unwrap();
    max - min <= 1
}

fn covered(vgm: &VgmFile, chip_id: i32, addr: i64) -> bool {
    for s in &vgm.roms {
        if s.chip as i32 == chip_id && s.kind == "c219" && !s.data.is_empty() {
            let start = s.start as i64;
            if start <= addr && addr < start + s.data.len() as i64 {
                return true;
            }
        }
    }
    false
}

fn decode_body(rom: &[u8], mask: i64, bank: i32, start: i32, frames: i32) -> Vec<u8> {
    let mut out = vec![0u8; frames as usize];
    for i in 0..frames {
        let idx = c219_rom_index(bank, start, i, mask);
        if idx >= 0 && (idx as usize) < rom.len() {
            out[i as usize] = rom[idx as usize];
        }
    }
    out
}

/// Bytes Furnace's C219 uploader reserves for one sample body.
///
/// `DivPlatformC140::renderSamples` uses `length8 + 4`, clamps a body to one
/// 128 KB bank and rounds an odd length up to an even one.
pub fn c219_furnace_length(smp: &C219Sample) -> usize {
    let mut length = smp.length() + 4;
    if length > C219_MAX_BODY {
        length = C219_MAX_BODY;
    }
    if length & 1 != 0 {
        length += 1;
    }
    length
}

/// Mirror Furnace's C219 sample upload.
///
/// Returns one `(bank, start_word, mem_pos, length)` per sample and the final
/// memory position. A body whose end crosses a 128 KB boundary is moved to the
/// next bank first.
fn c219_furnace_addresses(samples: &[C219Sample]) -> (Vec<(i32, i32, usize, usize)>, usize) {
    let mut out: Vec<(i32, i32, usize, usize)> = Vec::new();
    let mut mem_pos = 0usize;
    for smp in samples {
        let length = c219_furnace_length(smp);
        if (mem_pos & 0xFE0000) != ((mem_pos + length) & 0xFE0000) {
            mem_pos = (mem_pos + 0x1FFFF) & 0xFE0000;
        }
        let sample_off = mem_pos >> 1;
        out.push((
            ((sample_off >> 16) & 3) as i32,
            (sample_off & 0xFFFF) as i32,
            mem_pos,
            length,
        ));
        mem_pos += length;
    }
    (out, mem_pos)
}

/// Python `s.loop_start or -1`: zero is falsy.
fn loop_order(value: Option<i32>) -> i32 {
    match value {
        Some(v) if v != 0 => v,
        _ => -1,
    }
}

/// Keep each source sample bank in its own Furnace 128 KB bank.
///
/// Furnace switches a C219 group bank whenever a voice uses a sample from a
/// different bank; that switch silences the other voices in the group. The
/// source keeps all voices of a group on one bank, so samples from different
/// source banks must not share a Furnace bank.
///
/// A gap between banks is filled by appending trailing silence to a one-shot
/// body from the previous bank, not by adding a visible padding sample.
/// Looping bodies are never extended, because Furnace derives the chip end
/// address from the body length and extending one would move the loop. Groups
/// with a one-shot donor are placed first, so the groups that can only be last
/// are the ones without one.
///
/// Furnace rounds an odd body up to an even length. The gap is therefore sized
/// against that rounded length and stops one byte pair before the boundary;
/// ending exactly on the boundary would make Furnace move the donor itself
/// into the next bank and split its source group.
pub fn layout_c219_samples(samples: &[C219Sample]) -> Vec<C219Sample> {
    let mut by_bank: IndexMap<i32, Vec<C219Sample>> = IndexMap::new();
    for smp in samples {
        by_bank
            .entry(smp.source_bank)
            .or_default()
            .push(smp.clone());
    }
    let mut groups: Vec<(i32, Vec<C219Sample>, usize, bool)> = Vec::new();
    for (bank, group_samples) in by_bank {
        let total: usize = group_samples.iter().map(c219_furnace_length).sum();
        let one_shots = group_samples
            .iter()
            .any(|s| s.loop_start.is_none() && !s.noise);
        groups.push((bank, group_samples, total, one_shots));
    }
    groups.sort_by_key(|g| {
        (
            if g.3 { 0i8 } else { 1i8 },
            -(g.2 as i64),
            g.0,
        )
    });

    let mut out: Vec<C219Sample> = Vec::new();
    let mut mem_pos = 0usize;
    for (index, (bank, group_samples, _total, _has_one)) in groups.into_iter().enumerate() {
        // Play looping bodies first; a one-shot is the donor for the gap to
        // the next source bank and therefore goes last in this group.
        let mut ordered = group_samples;
        ordered.sort_by_key(|s| (s.loop_start.is_none(), s.start, loop_order(s.loop_start)));
        let target = index * C219_BANK_SIZE;
        if mem_pos < target {
            // Leave the two bytes Furnace's even-length rule needs; the next
            // sample's crossing check then aligns it to the bank boundary.
            let wanted_end = target - 2;
            let donor = out
                .iter()
                .rposition(|s| s.loop_start.is_none() && !s.noise);
            if let Some(di) = donor {
                let old_length = c219_furnace_length(&out[di]);
                let new_length = old_length + (wanted_end - mem_pos);
                let new_body = out[di].length().max(new_length - 4);
                let cur_length = out[di].length();
                out[di]
                    .data
                    .extend(std::iter::repeat_n(0u8, new_body - cur_length));
                mem_pos += c219_furnace_length(&out[di]) - old_length;
            } else {
                let pad_length = wanted_end - mem_pos;
                if pad_length >= 4 {
                    let pad = C219Sample {
                        start: 0,
                        data: vec![0u8; pad_length - 4],
                        source_bank: bank,
                        depth: 8,
                        source_length: pad_length - 4,
                        ..C219Sample::default()
                    };
                    mem_pos += c219_furnace_length(&pad);
                    out.push(pad);
                }
            }
        }
        for smp in ordered {
            let length = c219_furnace_length(&smp);
            if (mem_pos & 0xFE0000) != ((mem_pos + length) & 0xFE0000) {
                mem_pos = (mem_pos + 0x1FFFF) & 0xFE0000;
            }
            out.push(smp);
            mem_pos += length;
        }
    }
    out
}

/// Check the module's sample layout against Furnace's C219 uploader.
///
/// Furnace aligns a body to the next 128 KB bank when its end crosses a bank
/// boundary, and truncates a body longer than 128 KB. A source bank that lands
/// in more than one Furnace bank makes a group switch and silence its other
/// voices. Report those cases instead of silently losing samples.
pub fn c219_layout_warnings(samples: &[C219Sample]) -> Vec<String> {
    let mut warnings: Vec<String> = Vec::new();
    let (addresses, mem_end) = c219_furnace_addresses(samples);
    let furnace_bank: Vec<i32> = addresses.iter().map(|addr| addr.0).collect();
    for (i, (smp, (_bank, _start, _pos, _length))) in
        samples.iter().zip(addresses.iter()).enumerate()
    {
        if smp.length() + 4 > C219_MAX_BODY {
            warnings.push(format!(
                "C219 sample {i} is {} bytes; Furnace truncates a body over 128 KB",
                smp.length() + 4
            ));
        }
        if smp.loop_start.is_some() && smp.source_length != 0 && smp.length() != smp.source_length {
            warnings.push(format!(
                "C219 looping sample {i} gained {} bytes; its loop end moved",
                smp.length() as i64 - smp.source_length as i64
            ));
        }
    }
    if mem_end > C219_MEMORY {
        warnings.push(format!(
            "C219 sample bodies need {mem_end} bytes; Furnace's memory is 512 KB and truncates the tail"
        ));
    }
    let mut by_source: BTreeMap<i32, BTreeSet<i32>> = BTreeMap::new();
    for (i, smp) in samples.iter().enumerate() {
        if smp.hits.is_empty() {
            continue;
        }
        by_source
            .entry(smp.source_bank)
            .or_default()
            .insert(furnace_bank[i]);
    }
    for (bank, furnace_banks) in &by_source {
        if furnace_banks.len() > 1 {
            let sorted: Vec<i32> = furnace_banks.iter().copied().collect();
            warnings.push(format!(
                "C219 source bank {bank} spans Furnace banks {sorted:?}; group-bank switching can cut voices"
            ));
        }
    }

    // Furnace's C219 key-on writes the group's bank and then key-offs every
    // other active voice in that group. Replay the key-ons in time order to
    // find voices whose sample would be silenced by that switch.
    let mut events: Vec<(i64, i32, usize, i64)> = Vec::new();
    for (i, smp) in samples.iter().enumerate() {
        for h in &smp.hits {
            events.push((
                h.sample_time,
                h.voice,
                i,
                if h.off_sample != 0 {
                    h.off_sample
                } else {
                    C219_NEVER
                },
            ));
        }
    }
    events.sort_by_key(|e| (e.0, e.1));
    let mut group_bank = [0i32, 0, 0, 0];
    let mut active_until: HashMap<i32, i64> = HashMap::new();
    let mut cut_counts: BTreeMap<(i32, i32, i32), (i64, i64, i32)> = BTreeMap::new();
    let mut at_time: BTreeMap<i64, Vec<(i64, i32, usize, i64)>> = BTreeMap::new();
    for event in &events {
        at_time.entry(event.0).or_default().push(*event);
    }
    for (when, tick) in &at_time {
        let keying: BTreeSet<i32> = tick.iter().map(|e| e.1).collect();
        for &(_t, voice, index, off) in tick {
            let group = voice >> 2;
            let bank = furnace_bank[index];
            if group_bank[group as usize] != bank {
                for slot in 0..4 {
                    let other = (voice & !3) | slot;
                    if other == voice {
                        continue;
                    }
                    let Some(&until) = active_until.get(&other) else {
                        continue;
                    };
                    if until > *when && !keying.contains(&other) {
                        let key = (group, group_bank[group as usize], bank);
                        let entry = cut_counts.entry(key).or_insert((0, *when, other));
                        entry.0 += 1;
                    }
                }
                group_bank[group as usize] = bank;
            }
            active_until.insert(voice, off);
        }
    }
    for ((group, old_bank, new_bank), (count, when, voice)) in &cut_counts {
        let plural = if *count != 1 { "s" } else { "" };
        warnings.push(format!(
            "C219 voice group {group} switches from Furnace bank {old_bank} to {new_bank} at sample {when} and silences other active voices (first: voice {voice}, {count} cut{plural})"
        ));
    }
    warnings
}

/// Collect C219 hits and sample bodies from a parsed VGM.
pub fn collect_c219(vgm: &VgmFile) -> (Vec<C219Sample>, Vec<C219Off>, Vec<String>) {
    let ids: BTreeSet<i32> = vgm
        .writes
        .iter()
        .filter(|w| w.chip == "c219")
        .map(|w| w.chip_id as i32)
        .collect();
    let mut roms: IndexMap<i32, Vec<u8>> = IndexMap::new();
    for cid in ids {
        roms.insert(cid, assemble_rom(vgm, "c219", cid as u8, 0xFF, true, false));
    }
    let mut warnings: Vec<String> = Vec::new();
    let mut offs: Vec<C219Off> = Vec::new();
    if roms.is_empty() {
        return (Vec::new(), offs, warnings);
    }

    let mut reg = [[0i32; 16]; C219_VOICES];
    let mut keyed = [false; C219_VOICES];
    let mut hits: Vec<C219Hit> = Vec::new();
    // Python keeps references to the emitted hits and mutates `off_sample`
    // through them; indices into `hits` are the exact equivalent.
    let mut active: [Option<usize>; C219_VOICES] = [None; C219_VOICES];
    let mut vol_last = [(0i32, 0i32); C219_VOICES];
    let mut freq_last = [0i32; C219_VOICES];
    // 0x1F7 -> group 0, 0x1F1 -> group 1, 0x1F3 -> group 2, 0x1F5 -> group 3.
    let mut bank = [0i32; 4];

    for w in &vgm.writes {
        if w.chip != "c219" {
            continue;
        }
        let mut addr = w.reg as i32 & 0x1FF;
        // The 0x1F8/1F9/1FB/1FD mirrors alias the bank registers.
        if addr >= 0x1F8 && (addr & 1) != 0 {
            addr &= !0x08;
        }
        let group_bank = match addr {
            0x1F7 => Some(0usize),
            0x1F1 => Some(1),
            0x1F3 => Some(2),
            0x1F5 => Some(3),
            _ => None,
        };
        if let Some(group) = group_bank {
            bank[group] = w.val as i32 & 0x03;
            continue;
        }
        if addr >= 0x100 {
            continue;
        }
        let voice = (addr >> 4) as usize;
        let r = addr & 0x0F;
        let val = w.val as i32 & 0xFF;
        if r == 0x05 {
            if (val & C219_MODE_KEYON) != 0 {
                if let Some(index) = active[voice] {
                    hits[index].off_sample = w.sample;
                }
                let hit = C219Hit {
                    sample_time: w.sample,
                    chip_id: w.chip_id as i32,
                    voice: voice as i32,
                    start: (reg[voice][0x06] << 8) | reg[voice][0x07],
                    end: (reg[voice][0x08] << 8) | reg[voice][0x09],
                    loop_: (reg[voice][0x0A] << 8) | reg[voice][0x0B],
                    loop_on: (val & C219_MODE_LOOP) != 0,
                    bank: bank[voice / 4],
                    freq: (reg[voice][0x02] << 8) | reg[voice][0x03],
                    vol_l: reg[voice][0x01],
                    vol_r: reg[voice][0x00],
                    compressed: (val & C219_MODE_MULAW) != 0,
                    noise: (val & C219_MODE_NOISE) != 0,
                    invert: (val & C219_MODE_INVERT) != 0,
                    left_invert: (val & C219_MODE_L_INV) != 0,
                    off_sample: 0,
                    vol_pts: Vec::new(),
                    freq_pts: Vec::new(),
                };
                hits.push(hit);
                let index = hits.len() - 1;
                active[voice] = Some(index);
                vol_last[voice] = (hits[index].vol_l, hits[index].vol_r);
                freq_last[voice] = hits[index].freq;
                keyed[voice] = true;
            } else {
                if keyed[voice] {
                    offs.push(C219Off {
                        sample_time: w.sample,
                        chip_id: w.chip_id as i32,
                        voice: voice as i32,
                    });
                    if let Some(index) = active[voice] {
                        hits[index].off_sample = w.sample;
                        active[voice] = None;
                    }
                }
                keyed[voice] = false;
            }
            continue;
        }
        reg[voice][r as usize] = val;
        if keyed[voice] {
            if let Some(index) = active[voice] {
                let hit = &mut hits[index];
                if r == 0x00 || r == 0x01 {
                    let pair = (reg[voice][0x01], reg[voice][0x00]);
                    if pair != vol_last[voice] {
                        hit.vol_pts.push((w.sample, pair.0, pair.1));
                        vol_last[voice] = pair;
                    }
                } else if r == 0x02 || r == 0x03 {
                    let f = (reg[voice][0x02] << 8) | reg[voice][0x03];
                    if f != freq_last[voice] {
                        hit.freq_pts.push((w.sample, f));
                        freq_last[voice] = f;
                    }
                }
            }
        }
    }

    if hits.is_empty() {
        return (Vec::new(), offs, warnings);
    }
    if !roms.values().any(|r| !r.is_empty()) {
        warnings.push(
            "no C219 ROM block (0x8D); PCM notes will be silent until samples are added".into(),
        );
        return (Vec::new(), offs, warnings);
    }

    let mut by_key: IndexMap<
        (i32, i32, i32, i32, Option<i32>, bool, bool, bool),
        C219Sample,
    > = IndexMap::new();
    let mut undumped = 0i64;
    let mut clipped = 0i64;
    for h in &hits {
        let rom: &[u8] = roms.get(&h.chip_id).map(|r| r.as_slice()).unwrap_or(&[]);
        if rom.is_empty() {
            continue;
        }
        let mask = pow2_mask(rom.len());
        let base = c219_rom_index(h.bank, h.start, 0, mask);
        if base >= rom.len() as i64 || !covered(vgm, h.chip_id, base) {
            undumped += 1;
            continue;
        }
        let mut frames = (h.end - h.start) * 2;
        if frames <= 0 {
            frames = 2;
        }
        if frames as usize > C219_MAX_BODY {
            frames = C219_MAX_BODY as i32;
            clipped += 1;
        }
        let mut loop_off: Option<i32> = None;
        if h.loop_on && h.start <= h.loop_ && h.loop_ < h.end {
            let off = (h.loop_ - h.start) * 2;
            if off >= frames {
                loop_off = None;
            } else {
                loop_off = Some(off);
            }
        }
        let key = (
            h.chip_id,
            h.bank,
            h.start,
            h.end,
            loop_off,
            h.compressed,
            h.noise,
            h.loop_on,
        );
        if !by_key.contains_key(&key) {
            let body = if h.noise {
                vec![0u8; frames as usize]
            } else {
                let body = decode_body(rom, mask, h.bank, h.start, frames);
                if h.compressed {
                    body.iter().map(|&b| C219_MULAW[b as usize]).collect()
                } else {
                    body
                }
            };
            let depth = 8;
            let source_length = body.len();
            let smp = C219Sample {
                start: h.start,
                data: body,
                source_bank: h.bank,
                loop_start: loop_off,
                loop_end: if loop_off.is_some() {
                    Some(frames)
                } else {
                    None
                },
                depth,
                noise: h.noise,
                source_length,
                hits: Vec::new(),
            };
            by_key.insert(key, smp);
        }
        by_key.get_mut(&key).unwrap().hits.push(h.clone());
    }
    if undumped != 0 {
        warnings.push(format!(
            "{undumped} C219 triggers point at ROM that the VGM does not dump; those notes are silent"
        ));
    }
    if clipped != 0 {
        warnings.push(format!(
            "{clipped} C219 sample windows exceeded 128 KB and were truncated"
        ));
    }
    let total = by_key.len();
    let mut samples: Vec<C219Sample> = by_key
        .into_values()
        .filter(|s| s.noise || !is_silent_body(&s.data, s.depth))
        .collect();
    samples.sort_by_key(|s| (s.source_bank, s.start, loop_order(s.loop_start)));
    let silent_count = total - samples.len();
    if silent_count != 0 {
        warnings.push(format!(
            "{silent_count} silent C219 sample bodies were dropped"
        ));
    }
    (samples, offs, warnings)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::vgm::{ChipWrite, RomSlice};

    fn sample(source_bank: i32, start: i32, data: Vec<u8>, loop_start: Option<i32>) -> C219Sample {
        C219Sample {
            start,
            data,
            source_bank,
            loop_start,
            ..C219Sample::default()
        }
    }

    #[test]
    fn mulaw_table_matches_reference_expansion() {
        assert_eq!(C219_MULAW.len(), 256);
        assert_eq!(C219_MULAW[0], 0);
        assert_eq!(C219_MULAW[5], 1);
        assert_eq!(C219_MULAW[128], 0);
        assert_eq!(C219_MULAW[132], 255);
        assert_eq!(C219_MULAW[255], 134);
    }

    #[test]
    fn rate_and_clock_helpers_follow_reference() {
        assert!((c219_rate(0, 0x0100) - 339.85053168402777).abs() < 1e-12);
        assert_eq!(c219_furnace_clock(0), 98_833_972);
        assert_eq!(c219_furnace_clock(100_000_000), 100_000_000);
        assert!((c219_rate_scale(100_000_000) - 0.2535211267605634).abs() < 1e-12);
        assert_eq!(c219_rate_scale(25_056_500), 1.0);
    }

    #[test]
    fn step_writes_merge_and_refit_the_played_frequency() {
        let merged = merge_step_writes(&[(10, 100), (20, 200), (40, 300)], 16);
        assert_eq!(merged, vec![(20, 200), (40, 300)]);
        let hit = C219Hit {
            sample_time: 1000,
            freq: 0,
            freq_pts: vec![(1100, 0x1234)],
            ..C219Hit::default()
        };
        assert_eq!(hit_played_freq(&hit), 0x1234);
        let late = C219Hit {
            sample_time: 1000,
            freq: 0x0100,
            freq_pts: vec![(2000, 0x1234)],
            ..C219Hit::default()
        };
        assert_eq!(hit_played_freq(&late), 0x0100);
    }

    #[test]
    fn layout_pads_a_one_shot_donor_to_the_next_bank() {
        assert_eq!(c219_furnace_length(&sample(0, 0, vec![0; 10], None)), 14);
        assert_eq!(c219_furnace_length(&sample(0, 0, vec![0; 11], None)), 16);
        assert_eq!(
            c219_furnace_length(&sample(0, 0, vec![0; C219_MAX_BODY + 16], None)),
            C219_MAX_BODY
        );
        let out = layout_c219_samples(&[
            sample(0, 0x0100, vec![1; 10], None),
            sample(1, 0x0200, vec![2; 6], Some(0)),
        ]);
        let (addresses, mem_end) = c219_furnace_addresses(&out);
        assert_eq!(out.len(), 2);
        assert_eq!(addresses[0].0, 0);
        assert_eq!(addresses[1].0, 1);
        assert_eq!(out[0].data.len(), 131066);
        assert_eq!(out[1].source_bank, 1);
        assert_eq!(mem_end, C219_BANK_SIZE + 10);
    }

    #[test]
    fn collect_decodes_keyon_keyoff_and_drops_silent_bodies() {
        assert!(!is_silent_body(&[0], 8));
        assert!(is_silent_body(&[0, 0, 1], 8));
        assert!(is_silent_body(&[0x00, 0x00, 0x01, 0x00], 16));
        assert!(!is_silent_body(&[0x00, 0x00, 0x02, 0x00], 16));

        let mut vgm = VgmFile::default();
        let mut data = vec![0u8; 24];
        for (i, b) in [0u8, 1, 2, 3, 4, 5, 6, 7].iter().enumerate() {
            data[i] = *b;
        }
        vgm.roms.push(RomSlice {
            chip: 0,
            rom_size: 0,
            start: 0,
            data,
            kind: "c219",
            time: 0,
        });
        let mut write = |sample: i64, reg: u32, val: u32| {
            vgm.writes
                .push(ChipWrite::new(sample, "c219", 0, reg, val));
        };
        // Voice 0: start 0, end 4 words, frequency 0x0100, key-on.
        write(0, 0x06, 0x00);
        write(0, 0x07, 0x00);
        write(0, 0x08, 0x00);
        write(0, 0x09, 0x04);
        write(0, 0x02, 0x01);
        write(0, 0x03, 0x00);
        write(0, 0x05, 0x80);
        // Voice 1: start 8, end 12 words over a silent body, key-on.
        write(10, 0x16, 0x00);
        write(10, 0x17, 0x08);
        write(10, 0x18, 0x00);
        write(10, 0x19, 0x0C);
        write(10, 0x15, 0x80);
        // Voice 0 key-off.
        write(100, 0x05, 0x00);

        let (samples, offs, warnings) = collect_c219(&vgm);
        assert_eq!(samples.len(), 1);
        assert_eq!(samples[0].data, vec![1, 0, 3, 2, 5, 4, 7, 6]);
        assert_eq!(samples[0].start, 0);
        assert_eq!(samples[0].loop_start, None);
        assert_eq!(samples[0].mode_freq(), 0x0100);
        assert_eq!(samples[0].c4_rate(0), 1000);
        assert_eq!(offs.len(), 1);
        assert_eq!(offs[0].sample_time, 100);
        assert_eq!(offs[0].voice, 0);
        assert_eq!(
            warnings,
            vec!["1 silent C219 sample bodies were dropped".to_string()]
        );
    }
}
