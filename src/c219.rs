// A frequency write this soon after key-on is the note's own pitch.
pub const C219_REFIT_SAMPLES: i64 = 735;
pub const C219_MAX_BODY: usize = 131072;
pub const C219_BANK_SIZE: usize = 0x20000;
pub const C219_MEMORY: usize = 0x80000;
pub const C219_NEVER: i64 = 1 << 62;

/// Reference byte rate for a C219 frequency register, in bytes/second.
pub fn c219_rate(clock: u32, freq: i32) -> f64 {
    let clock = if clock == 0 { C219_DEFAULT_CLOCK } else { clock };
    (clock as f64) * ((freq & 0xFFFF) as f64) / (C219_RATE_DIVISOR as f64)
}

/// Furnace-notation C219 clock (1136/288 of the VGM clock, clamped).
pub fn c219_furnace_clock(clock: u32) -> u32 {
    let clock = if clock == 0 { C219_DEFAULT_CLOCK } else { clock };
    let wanted = (clock as u64) * (C219_FURNACE_CLOCK_SCALE.0 as u64)
        / (C219_FURNACE_CLOCK_SCALE.1 as u64);
    1_000_000u64.max((C219_FURNACE_CLOCK_MAX as u64).min(wanted)) as u32
}

/// Sample-rate correction when the custom clock had to be clamped.
///
/// A stored sample C-4 rate and the note chosen from it are a ratio. Scaling
/// the stored rate by the platform/reference rate ratio cancels the clamp.
pub fn c219_rate_scale(clock: u32) -> f64 {
    let clock = if clock == 0 { C219_DEFAULT_CLOCK } else { clock };
    let wanted = (clock as f64) * (C219_FURNACE_CLOCK_SCALE.0 as f64)
        / (C219_FURNACE_CLOCK_SCALE.1 as f64);
    if wanted <= C219_FURNACE_CLOCK_MAX as f64 {
        return 1.0;
    }
    C219_FURNACE_CLOCK_MAX as f64 / wanted
}

fn pow2_mask(size: usize) -> i64 {
    if size == 0 {
        return 0;
    }
    let bits = 64 - (size as u64 - 1).leading_zeros() as i32;
    (1i64 << bits) - 1
}

/// libvgm find_sample for the 219: 128 KB banks, byte addresses.
pub fn c219_rom_index(bank: i32, start_word: i32, byte_offset: i32, mask: i64) -> i64 {
    ((((bank & 0x03) as i64) << 17) | ((start_word & 0xFFFF) as i64 * 2 + byte_offset as i64))
        & mask
}

/// Merge MSB/LSB frequency write pairs.
pub fn merge_step_writes(pts: &[(i64, i32)], gap: i64) -> Vec<(i64, i32)> {
    let mut merged: Vec<(i64, i32)> = Vec::new();
    for p in pts {
        if let Some(last) = merged.last_mut() {
            if p.0 - last.0 <= gap {
                *last = *p;
                continue;
            }
        }
        merged.push(*p);
    }
    merged
}

/// The frequency a hit actually plays at, after the post-key-on refit.
pub fn hit_played_freq(hit: &C219Hit) -> i32 {
    let steps = merge_step_writes(&hit.freq_pts, 16);
    if !steps.is_empty()
        && steps[0].1 != 0
        && (steps[0].0 - hit.sample_time <= C219_REFIT_SAMPLES || (hit.freq & 0xFFFF) == 0)
    {
        return steps[0].1;
    }
    hit.freq & 0xFFFF
}

